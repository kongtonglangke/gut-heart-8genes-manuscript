def load(name, folder=T):
    with open(os.path.join(folder, name), encoding="utf-8") as f:
        return list(csv.DictReader(f))


def sci(p, digits=2):
    """Format a P value: plain decimals above 0.01, scientific notation below."""
    try:
        v = float(p)
    except (TypeError, ValueError):
        return str(p)
    if v == 0:
        return "0"
    if v >= 0.1:
        return ("%.3f" % v).rstrip("0").rstrip(".") if v < 1 else "%.2f" % v
    mant, exp = ("%e" % v).split("e")
    mant = ("%.2f" % float(mant)).rstrip("0").rstrip(".")
    return "%s x 10^%d" % (mant, int(exp))


def ratio(x):
    v = float(x)
    return ("%.2f" % v) if v < 1 else ("%.1f" % v)


