def sci_p_display(p):
    """Table 5 style: decimals above 1e-3, scientific notation at or below."""
    try:
        v = float(p)
    except (TypeError, ValueError):
        return str(p)
    if v == 0:
        return "0"
    if v >= 1e-3:
        return ("%.3f" % v).rstrip("0").rstrip(".") if v < 1 else "%.2f" % v
    mant, exp = ("%e" % v).split("e")
    return "%s x 10^%d" % (("%.2f" % float(mant)).rstrip("0").rstrip("."), int(exp))


def count_harmonised(eqtl_file, outcome_file):
    """Recompute the number of harmonised variants entering the FES control test."""
    import math
    e = load(eqtl_file, RAW_GTEX)
    o = load(outcome_file, RAW_OUT)
    def usable(rows):
        out = {}
        for r in rows:
            try:
                se, beta, pv = float(r.get("se", "")), float(r.get("beta", "")), float(r.get("p", ""))
            except (TypeError, ValueError):
                continue
            if math.isfinite(se) and math.isfinite(beta) and math.isfinite(pv) and se > 0:
                out[(r["pos"], r["ref"].upper(), r["alt"].upper())] = r
        return out
    E, O = usable(e), usable(o)
    n, seen = 0, set()
    for (pos, ref, alt) in E:
        if pos in seen:
            continue
        for (p2, r2, a2) in [k for k in O if k[0] == pos]:
            ro = O[(p2, r2, a2)]
            if not ((ref == r2 and alt == a2) or (ref == a2 and alt == r2)):
                continue
            try:
                af = float(ro.get("af", "nan"))
            except (TypeError, ValueError):
                continue
            maf = min(af, 1 - af)
            if not (maf > 0.005 and maf < 0.995):
                continue
            n += 1
            seen.add(pos)
            break
    return n


def numfmt(x, digits=3):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return str(x)
    if abs(v) >= 1000:
        return "{:,.0f}".format(v)
    return ("%.*f" % (digits, v)).rstrip("0").rstrip(".") if v != int(v) else "%d" % int(v)


